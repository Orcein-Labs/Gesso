# scripts/env-vars.jl: regenerate docs/env-vars.md, the index of every
# GESSO_* environment variable the code reads. Entry: `make env-vars`.
#
#   julia scripts/env-vars.jl           rewrite docs/env-vars.md
#   julia scripts/env-vars.jl --check   exit 1 if docs/env-vars.md is stale
#
# The index lists each name and the files that mention it. Defaults and
# meaning live at the read site, so the table cannot drift from them.

const ROOT = dirname(@__DIR__)
const DIRS = ["src", "ext", "scripts", "test", "benchmark"]
const OUT = joinpath(ROOT, "docs", "env-vars.md")
const PATTERN = r"\bGESSO_[A-Z0-9_]*[A-Z0-9]\b"

function scan()
    seen = Dict{String, Set{String}}()
    for d in DIRS, (dir, _, files) in walkdir(joinpath(ROOT, d)), f in files
        endswith(f, ".jl") || continue
        path = joinpath(dir, f)
        rel = replace(relpath(path, ROOT), '\\' => '/')
        for m in eachmatch(PATTERN, read(path, String))
            push!(get!(Set{String}, seen, m.match), rel)
        end
    end
    return seen
end

function render(seen)
    io = IOBuffer()
    println(io, "# Environment variables")
    println(io)
    println(
        io,
        "Every `GESSO_*` variable the code, tests and benchmarks mention. This file is generated by",
    )
    println(
        io,
        "`julia scripts/env-vars.jl` and checked in CI, so do not edit it by hand. The default and",
    )
    println(io, "meaning of each variable are documented where it is read.")
    println(io)
    println(io, "Backend variables. `GESSO_BACKEND` picks the backend for the scripts and the chat")
    println(io, "server. It is `lava` when unset, the GPU default. `cpu` is the correctness oracle.")
    println(io, "`cuda` is an optional comparator and runs only when asked for. A variable listed")
    println(io, "only with `ext/cuda_*` files applies to the CUDA path. New GPU work goes into Lava.")
    println(io)
    println(io, "| Variable | Mentioned in |")
    println(io, "|---|---|")
    for name in sort!(collect(keys(seen)))
        files = join(("`$f`" for f in sort!(collect(seen[name]))), ", ")
        println(io, "| `", name, "` | ", files, " |")
    end
    return String(take!(io))
end

text = render(scan())
if "--check" in ARGS
    current = isfile(OUT) ? read(OUT, String) : ""
    if current != text
        println(stderr, "docs/env-vars.md is stale; run `julia scripts/env-vars.jl`")
        exit(1)
    end
    println("docs/env-vars.md is current")
else
    write(OUT, text)
    println("wrote docs/env-vars.md")
end
